export function composeMonthClosure(stem: string, branch: string, yearBranch: string, action: string,
  mode?: MonthObservationMode): string {
  const group = TEN_GOD_GROUP[yearBranch], outcome = ALTERNATE[yearBranch]?.[branch] ?? OUTCOME[group]?.[branch];
  if (!outcome) return "";
  const route = mode === "head-curved" && branch === "식신" ? "받은 순서를 조금 달리해 편해진 곳을 자신의 예로 설명하면, 배운 답을 기억하는 것과 직접 이해한 것을 다른 사람에게 전하는 경험이 구별됩니다."
    : mode === "head-straight" && branch === "식신" ? "왜 필요한지 알게 된 한 순서를 직접 이어 해 보면, 더 읽어야 할 내용과 이미 손으로 익혀도 되는 부분이 분명해집니다."
    : mode === "head-curved" ? "대화 중 떠오른 작은 예로 뜻이 구체화됐어도 그 답을 듣고 남은 감정은 따로 꺼낼 수 있습니다."
    : mode === "head-straight" ? "짧게 되짚은 뜻이 상대의 답과 같아지면 더 추측할 내용과 이미 서로 알아들은 내용이 구분됩니다."
      : mode === "heart-curved" ? "도움을 청한 마음을 들어 줬다는 느낌은 문제를 잘 해결해 준 고마움과 다른 가까움입니다."
        : mode === "heart-straight" ? "기억해 달라고 한 작은 일을 상대도 알아본다면 조용한 배려가 서로 오갈 자리가 생깁니다." : null;
  // A relation with expression+resources stays with the object/use scene.
  const choice = TEN_GOD_GROUP[stem] === "식상" && TEN_GOD_GROUP[branch] === "재성"
    ? stem === "상관" ? "모양을 전부 바꾸기 전에 실제로 고친 불편을 작은 예로 보여 줄 수 있습니다."
      : "더 많은 양을 나누기 전에 만든 사람과 쓴 사람이 각각 좋았던 부분을 들어 볼 수 있습니다."
    : `${action}을 떠올려 보세요.`;
  return `${route ?? choice} ${outcome}`;
}
