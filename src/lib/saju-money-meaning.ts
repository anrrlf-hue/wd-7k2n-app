import type { ReportParagraph } from "@/lib/free-report-schema";
import type { PremiumEditorialPlan } from "@/lib/premium-editorial-plan";

/** Separate earning, preserving resources and choosing expenses before copy is
 * composed. The natal plan selects a lens, never a balance or spending history. */
export function buildSajuMoneyMeaning(plan: PremiumEditorialPlan): {
  structure: ReportParagraph;
  keeping: ReportParagraph;
  spending: ReportParagraph;
  premiumManagement: string;
  premiumSpending: string;
} {
  const c = plan.natalEvidence.counts;
  const evidence = `해석 계획 ${plan.id}; 재성 ${c.재성}개 · 관성 ${c.관성}개 · 인성 ${c.인성}개 · 식상 ${c.식상}개 · 비겁 ${c.비겁}개. 실제 소득·자산·지출 내역을 사용하지 않았습니다.`;
  const structure = c.관성 > Math.max(c.재성, c.인성, c.식상, c.비겁)
    ? "돈의 이야기에서는 눈에 띄는 보상보다 맡은 역할을 이어가는 기준이 먼저 읽힙니다. 결과를 잘 마무리하는 일, 그 결과의 대가를 받는 일, 다음에도 이어갈 자원을 남기는 일은 각각 다른 선택입니다. 신뢰를 얻었다는 느낌만으로 실제 남는 몫까지 알 수는 없습니다."
    : c.재성 === 0
      ? "이 구성에서 돈과 직접 교환을 뜻하는 요소는 드러나지 않아, 기회를 알아보는 감각이나 자산의 크기를 정하지 않습니다. 대신 해낸 일이 누구에게 쓰이는지와 어떤 대가로 이어질지 별도로 설명하는 장면에 초점을 둡니다. 익숙한 일을 잘해내는 것만으로 교환 조건이 정해지지는 않습니다."
      : c.재성 >= Math.max(c.관성, c.인성, c.식상, c.비겁)
        ? "실제 쓰임과 돌아올 결과를 살피는 상징이 두드러집니다. 제안의 겉보기 대가를 비교하는 단계와 그것을 이어가는 비용을 빼고 남을 몫을 보는 단계는 다릅니다. 같은 보상이라도 준비와 유지에 필요한 조건이 달라지면 선택의 의미도 달라질 수 있습니다."
        : "돈과 교환의 상징은 다른 기준과 함께 놓입니다. 일을 택한 이유가 마음에 든다고 그 조건도 충분하다는 뜻은 아니고, 대가가 크다고 오래 이어갈 수 있다는 뜻도 아닙니다. 납득한 내용과 실제 남을 몫을 따로 살펴보는 재물 관점입니다.";
  const keeping = c.관성 > 0
    ? "이미 맡은 약속과 새 지출이 겹치는 상황을 떠올려보세요. 당장 쓸 수 있어 보이는 몫에서도 기존 일을 마칠 시간·자료에 필요한 부분을 먼저 구분하면, 새 선택 때문에 이전 약속의 준비를 다시 줄여야 하는 일을 피할 수 있습니다. 무엇을 남기는지는 실제 일정과 비용을 보고 정해야 합니다."
    : "다음 결과를 만들 준비와 새 지출이 겹친다면, 한 번 쓰고 끝날 비용과 다시 필요한 자원을 나누어볼 수 있습니다. 모두 현재 쓸 수 있는 몫으로 보면 다음 작업을 시작할 때 같은 준비가 다시 필요해질 수 있습니다. 실제로 남길 양은 자신의 기록과 조건을 보고 정합니다.";
  const spending = c.인성 > 0
    ? "배움이나 준비를 위해 도구·수업을 고르는 상황이라면, 이번에 적용할 작업 하나가 있는지 먼저 살펴보세요. 적용할 자리가 분명하면 비용의 쓰임을 확인할 수 있지만, 더 준비됐다는 느낌만을 위해 선택하면 공부는 늘고 실제 시도는 미뤄질 수 있습니다. 구매 전 작은 적용으로 부족한 부분을 확인해볼 수 있습니다."
    : c.비겁 > 0
      ? "함께 쓸 비용을 고르는 상황에서는 내가 원하는 방식과 공동으로 필요한 부분이 다를 수 있습니다. 모두 같은 선택을 원한다고 가정해 지출하기보다 각자 사용할 부분을 먼저 구분하면, 돈을 쓴 뒤에 부담의 이유를 다시 설명하는 일을 줄일 수 있습니다."
      : "새 물건이나 서비스를 고르는 상황이라면, 처음 해결하려던 불편과 추가 기능의 매력을 나누어볼 수 있습니다. 꼭 필요한 쓰임이 충족된다면 더 많은 기능에 드는 비용은 별도 선택입니다. 실제 사용할 장면을 먼저 그려보면 준비를 넓히는 지출과 목적을 해결하는 지출을 구별하기 쉽습니다.";
  const premiumManagement = c.관성 > 0
    ? "관리에서는 매달 나가는 비용과 이번에만 쓸 수 있는 몫을 나누어 봅니다. 가령 돈이 들어와 여유로워 보이는 날에도 이미 이용 중인 서비스나 생활비가 뒤에 남아 있다면, 지금의 잔액과 자유롭게 쓸 수 있는 금액은 다를 수 있습니다. 반복 비용을 먼저 한 줄로 적어 따로 남기는 선택은 새 지출 뒤에 다시 빠듯해지는 이유를 알아보게 합니다. 모두 다른 일에 쓰는 선택과 비교하면 편리함을 지금 누리는 만족과 다음 달에도 마음 놓는 만족이 다르게 남을 수 있습니다. 실제 금액은 자신의 기록으로 정해야 합니다."
    : "관리에서는 지금 쓰는 만족과 다음에도 쓸 여유를 나누어 봅니다. 가령 한 번에 넉넉히 마련하는 선택이 편해 보여도 실제로 자주 쓰는 것은 일부일 수 있습니다. 작은 양부터 쓰고 남는 몫을 따로 두는 선택은 필요한 것이 달라졌을 때 바꿀 여지를 남깁니다. 한 번의 편리함을 택하는 것과 다음 선택의 여유를 남기는 것은 다른 만족이며, 이 구성으로 자산이나 소비 습관을 확정하지 않습니다.";
  const premiumSpending = c.인성 > 0
    ? "지출에서는 더 준비됐다는 안심과 실제로 해 볼 수 있게 된 경험을 나누어 봅니다. 가령 새 수업이나 도구를 고를 때 부족한 부분이 확인됐다면 그 부분을 메우는 비용이 다음 시도에 도움이 될 수 있습니다. 하지만 아직 한 번도 적용하지 않았다면, 구매 전에 작은 시험을 해 보는 선택이 필요했던 도움과 막연한 걱정을 가려줄 여지가 있습니다. 돈을 쓴 뒤 안심한 순간과 배운 것을 직접 쓴 순간 중 어느 쪽이 더 오래 만족으로 남았는지 돌아보세요."
    : c.비겁 > 0
      ? "지출에서는 함께 고르는 즐거움과 실제로 각자가 쓰는 정도를 나누어 봅니다. 가령 가까운 사람과 물건을 같이 사며 내 취향에 잘 맞는 것을 골랐는데 상대는 거의 쓰지 않으면, 좋은 선택이라는 만족 옆에 혼자만 원했던 것 같다는 어색함이 남을 수 있습니다. 각자의 사용 장면을 먼저 들어 보는 선택은 비용을 나누기 전에 함께 쓰는 이유를 알게 합니다. 자신의 취향을 포기하기보다 개인적으로 갖고 싶은 것과 함께 필요한 것을 구별해볼 수 있습니다."
      : "지출에서는 새로 갖추는 기쁨과 지금 불편을 줄이는 만족을 나누어 봅니다. 가령 묶음 서비스의 여러 기능이 매력적이어도 당장 쓸 것은 하나일 수 있습니다. 필요한 것부터 써 보는 선택은 실제로 편해진 장면을 확인한 뒤 다음 비용을 고를 시간을 남깁니다. 많이 갖추는 선택과 비교하면 준비한 것의 수보다 생활이 얼마나 달라졌는지를 알아볼 여지가 있습니다.";
  return { structure: { text: structure, evidence }, keeping: { text: keeping, evidence },
    spending: { text: spending, evidence }, premiumManagement, premiumSpending };
}
