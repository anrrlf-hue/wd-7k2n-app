const isGod = (v?: string): v is God => Boolean(v && Object.hasOwn(GOD, v));

/** Select sources before prose. A visible absence is not a lack of ability;
 * hidden stems, unknown hours and unused relations never acquire extra weight. */
export function buildNatalNarrativeFrame(facts: SajuFacts) {
  const plan = buildCustomerReadingPlan(facts);
  const planCopy = renderCustomerPlanCopy(facts, plan);
  const pillars = facts.pillars.filter(p => facts.hasTimeInput || p.pillar !== "hour");
  const month = pillars.find(p => p.pillar === "month"), day = pillars.find(p => p.pillar === "day");
  const hour = pillars.find(p => p.pillar === "hour");
  const counts = countsFor(facts);
  const maximum = Math.max(...Object.values(counts));
  const leaders = (Object.keys(counts) as TenGodGroup[]).filter(g => counts[g] === maximum && maximum > 0);
  const workGod = isGod(month?.branchTenGod) ? month.branchTenGod : isGod(month?.stemTenGod) ? month.stemTenGod : null;
  const closeGod = isGod(day?.branchTenGod) ? day.branchTenGod : null;
  const stem = STEM[facts.dayStem] ?? { name: facts.dayStemKo, center: "자기에게 소중한 것을 살피는 마음", shadow: "여러 바람을 함께 품는 긴장", feeling: "소중하게 여기는 마음" };
  const branches = new Set(pillars.map(p => p.branchHanja));
  // The actual relation string is required; three glyphs alone do not assert
  // transformation, success or a strength diagnosis.
  const fireMeeting = ["巳", "午", "未"].every(b => branches.has(b)) && facts.keyRelations.some(r => /巳午未.*(방합|화국)/.test(r));
  const evidence: Record<Theme, string> = {
    self: `일간 ${facts.dayStem}; 오행 ${Object.entries(facts.fiveElements).map(([element, count]) => `${element} ${count}개`).join(" · ")}; ${facts.dayStrengthReliable ? `강약 ${({ strong: "강한 편", weak: "약한 편", neutral: "중화" })[facts.dayStrength]}` : "출생시간 미상으로 강약 미사용"}${fireMeeting ? "; 확인 관계 巳午未 방합" : ""}`,
    relationship: `일주 ${day?.ganzhi ?? "미확인"}; 일지 ${day?.branchHanja ?? "미확인"}/${closeGod ?? "미확인"}; 일간 ${facts.dayStem}; 표현 식상 ${counts.식상}, 신뢰 관성 ${counts.관성}, 이해 인성 ${counts.인성}, 자기 선택 비겁 ${counts.비겁}`,
    money: `드러난 재성 ${counts.재성}, 식상 ${counts.식상}, 비겁 ${counts.비겁}, 관성 ${counts.관성}, 인성 ${counts.인성}; ${hour ? `시주 ${hour.ganzhi}/${hour.stemTenGod}/${hour.branchTenGod}` : "시주 미사용"}`,
    work: `월주 ${month?.ganzhi ?? "미확인"}/${month?.stemTenGod ?? "미확인"}/${workGod ?? "미확인"}; 일간 ${facts.dayStem}; 드러난 식상 ${counts.식상}, 비겁 ${counts.비겁}, 인성 ${counts.인성}`,
    life: `드러난 식상 ${counts.식상}, 인성 ${counts.인성}; ${facts.dayStrengthReliable ? `강약 ${({ strong: "강한 편", weak: "약한 편", neutral: "중화" })[facts.dayStrength]}` : "강약 미사용"}; 생활 리듬의 상징 해석, 의료 진단 아님`,
  };
  return { facts, stem, counts, leaders, month, day, hour, workGod, closeGod, fireMeeting, evidence, plan, planCopy };
}
